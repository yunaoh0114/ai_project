# -----------------------------
# 지도 생성
# -----------------------------
m = folium.Map(
    location=[37.5665, 126.9780],
    zoom_start=11,
    tiles="OpenStreetMap"
)

# 파란색 마커 추가
for name, info in places.items():
    folium.Marker(
        location=[info["lat"], info["lon"]],
        popup=f"<b>{name}</b><br>{info['desc']}",
        tooltip=name,
        icon=folium.Icon(
            color="blue",
            icon="info-sign"
        )
    ).add_to(m)

# -----------------------------
# 지도 출력 (60% 크기)
# -----------------------------
col1, col2 = st.columns([3, 2])

with col1:
    st_folium(m, width=700, height=500)

